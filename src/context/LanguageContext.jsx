export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    return localStorage.getItem('gt_lang') || 'en'
  })

  const setLang = (newLang) => {
    setLangState(newLang)
    localStorage.setItem('gt_lang', newLang)
  }

  useEffect(() => {
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr'
    document.documentElement.lang = lang
  }, [lang])

  const t = (key) => {
    return translations[lang]?.[key] || translations['en']?.[key] || key
  }

  const tCity = (cityName) => {
    if (!cityName) return ''
    const entry = cityTranslations[cityName] || cityTranslations[cityName.trim()]
    if (entry) {
      return entry[lang] || entry['en'] || cityName
    }
    return cityName
  }

  return (
    <LanguageContext.Provider value={{ lang, setLang, t, tCity }}>
      {children}
    </LanguageContext.Provider>
  )
}

export const useLanguage = () => useContext(LanguageContext)
